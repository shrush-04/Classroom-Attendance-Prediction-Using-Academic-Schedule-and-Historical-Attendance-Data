import pandas as pd
import numpy as np
import os
import sys

def engineer_features(input_path, output_path=None):
    """
    Reads cleaned attendance data, engineers features, and saves.
    Strictly avoids data leakage: sorts chronologically, shifts target-derived variables.
    """
    if output_path is None:
        output_path = os.path.join(os.path.dirname(os.path.dirname(input_path)), "processed", "feature_engineered_attendance.csv")
    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    print(f"Reading file for feature engineering: {input_path}...")
    df = pd.read_csv(input_path)

    # Ensure chronological order
    df['Datetime'] = pd.to_datetime(df['Date'].astype(str) + ' ' + df['Start_Time'].astype(str))
    df = df.sort_values(by=['Section', 'Datetime']).reset_index(drop=True)

    # 1. Day of Week (standardized categorical and integer index)
    # df['Day_of_Week'] is already in the data. We will also extract day of week integer.
    df['Day_of_Week_Int'] = pd.to_datetime(df['Date']).dt.dayofweek

    # 2. Day of Semester (days elapsed since first date in dataset)
    first_date = pd.to_datetime(df['Date']).min()
    df['Day_of_Semester'] = (pd.to_datetime(df['Date']) - first_date).dt.days + 1

    # 3. Week Number
    df['Week_Number'] = pd.to_datetime(df['Date']).dt.isocalendar().week

    # 4. Time slot indicators
    start_hour = pd.to_datetime(df['Start_Time'], format='%H:%M').dt.hour
    df['Time_of_Day'] = np.where(start_hour < 12, 'Morning', 'Afternoon')
    df['Is_Morning'] = np.where(start_hour < 12, 1, 0)
    df['Is_Afternoon'] = np.where(start_hour >= 12, 1, 0)

    # 5. Holiday indicators
    # Identify dates that are holidays
    holiday_dates = pd.to_datetime(df[df['Holiday_Before_After'].isin(['Holiday_Before', 'Both', 'Holiday_After'])]['Date']).unique()
    
    def get_days_since_holiday(row_date):
        row_dt = pd.to_datetime(row_date)
        past_holidays = holiday_dates[holiday_dates < row_dt]
        if len(past_holidays) == 0:
            return 14.0 # default value if no holiday has occurred yet
        return float((row_dt - past_holidays.max()).days)

    df['Days_Since_Last_Holiday'] = df['Date'].apply(get_days_since_holiday)

    # 6. Week Before Exam
    exam_dates = pd.to_datetime(df[df['Internal_Test_Week'] == 1]['Date']).unique()
    
    def get_is_week_before_exam(row_date):
        row_dt = pd.to_datetime(row_date)
        future_exams = exam_dates[exam_dates >= row_dt]
        if len(future_exams) == 0:
            return 0
        days_to_exam = (future_exams.min() - row_dt).days
        return 1 if 0 < days_to_exam <= 7 else 0

    df['Week_Before_Exam'] = df['Date'].apply(get_is_week_before_exam)

    # 7. Consecutive Lecture Count (lectures for that section on that day)
    df['Consecutive_Lecture_Count'] = df.groupby(['Section', 'Date'])['Lecture_Number'].transform('count')

    # 8. LAG FEATURES (Shifted to avoid leakage!)
    # previous attendance percentage
    df['Previous_Lecture_Attendance_Percentage'] = df.groupby('Section')['Attendance_Percentage'].shift(1)

    # gap in hours since last lecture for this section
    df['Gap_Since_Previous_Lecture_Hours'] = df.groupby('Section')['Datetime'].diff().dt.total_seconds() / 3600.0

    # 9. ROLLING FEATURES (Shifted target to prevent leakage)
    # rolling average of past 3 classes for this section & subject
    df['Rolling_Average_Previous_3_Lectures'] = df.groupby(['Section', 'Subject'])['Attendance_Percentage'].shift(1).rolling(3, min_periods=1).mean()

    # 10. HISTORICAL AVERAGES (Shifted target to prevent leakage)
    # expanding historical mean of attendance per subject & section
    df['Subject_Historical_Average'] = df.groupby(['Section', 'Subject'])['Attendance_Percentage'].shift(1).expanding().mean().reset_index(level=0, drop=True)

    # Clean up auxiliary column
    df = df.drop(columns=['Datetime'])

    # Save engineered dataset
    df.to_csv(output_path, index=False)
    print(f"Feature engineering completed. File saved to: {output_path}")

    # Create feature dictionary
    create_feature_dictionary(os.path.join(os.path.dirname(os.path.dirname(output_path)), "outputs"))
    return True

def create_feature_dictionary(output_dir):
    os.makedirs(output_dir, exist_ok=True)
    dict_path = os.path.join(output_dir, "feature_dictionary.md")
    
    content = """# Feature Dictionary

This document details the engineered features generated by the feature engineering pipeline. All features are designed to avoid data leakage and use only information available *prior* to the lecture session.

| Feature Name | Description | Calculation / Derived From | Leakage Prevention |
| :--- | :--- | :--- | :--- |
| **Day_of_Week_Int** | Day of week as integer (0-5, Mon-Sat) | Extracted from `Date` | Date metadata only, no leakage. |
| **Day_of_Semester** | Chronological day index starting at 1 | Difference in days between `Date` and the start of the semester | Calendar field, no leakage. |
| **Week_Number** | ISO calendar week number of the year | Extracted from `Date` | Calendar field, no leakage. |
| **Time_of_Day** | Slot category (Morning or Afternoon) | Derived from `Start_Time` (<12:00 vs >=12:00) | Schedule field, no leakage. |
| **Is_Morning** | Binary indicator for morning class | `Start_Time` hour < 12 | Schedule field, no leakage. |
| **Is_Afternoon** | Binary indicator for afternoon class | `Start_Time` hour >= 12 | Schedule field, no leakage. |
| **Days_Since_Last_Holiday** | Days elapsed since the most recent holiday | Difference in days from current `Date` to the nearest past date where `Holiday_Before_After` != None | Employs only past holiday dates. |
| **Week_Before_Exam** | Binary indicator if an exam falls in next 7 days | Checks if any future row with `Internal_Test_Week` == 1 is within 7 days | Uses scheduled exam calendar dates (pre-planned). |
| **Consecutive_Lecture_Count**| Number of lectures scheduled on that day for the Section | Count of rows grouped by `Section` and `Date` | Derived from pre-planned timetable, no leakage. |
| **Previous_Lecture_Attendance_Percentage** | Attendance rate of the immediately preceding lecture for this Section | `df.groupby('Section')['Attendance_Percentage'].shift(1)` | **Shifted by 1:** uses only historical target value. |
| **Gap_Since_Previous_Lecture_Hours** | Hours elapsed since the section's last lecture | Time delta between current `Start_Time` and previous lecture's `End_Time` | Schedule field, no leakage. |
| **Rolling_Average_Previous_3_Lectures** | Moving average of attendance in the previous 3 sessions of this Subject | Shifted attendance rate rolled with window size 3 and mean aggregation | **Shifted by 1:** excludes current attendance. |
| **Subject_Historical_Average** | Cumulative running average of attendance in this Subject | Expanding mean of shifted attendance rate | **Shifted by 1:** excludes current attendance. |
"""
    with open(dict_path, 'w', encoding='utf-8') as f:
        f.write(content)
    print(f"Feature dictionary written to: {dict_path}")

if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python feature_engineering.py <path_to_cleaned_data>")
        sys.exit(1)
    cleaned_path = sys.argv[1]
    engineer_features(cleaned_path)
